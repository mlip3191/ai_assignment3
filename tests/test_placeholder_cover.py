"""Tests for the committed placeholder cover (PROJECT.md 8.2, task C4, REC-6 on #4).

The placeholder is shown when a song has no cover yet or FLUX fails. It is drawn by a person, not
generated by any model, so these tests only check what can be checked: it exists, it is a small
square PNG the browser can show, and lane C owns it.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts" / "github"))

from merge_owner import CODEOWNERS, owners_of, parse  # noqa: E402

PLACEHOLDER = ROOT / "jukebox" / "assets" / "placeholder_cover.png"
MAX_BYTES = 500_000  # it ships in the ZIP and loads in every library row


def test_placeholder_is_a_square_png() -> None:
    data = PLACEHOLDER.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    assert data[12:16] == b"IHDR"
    width, height = struct.unpack(">II", data[16:24])
    assert width == height and width >= 256


def test_placeholder_is_small() -> None:
    assert 0 < PLACEHOLDER.stat().st_size <= MAX_BYTES


def test_lane_c_owns_the_placeholder() -> None:
    rules = parse(CODEOWNERS.read_text(encoding="utf-8"))
    assert owners_of("jukebox/assets/placeholder_cover.png", rules) == ["felcervino"]
